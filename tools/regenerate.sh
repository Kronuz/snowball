#!/bin/sh
# Regenerates generated/ and runtime/ from the Snowball sources at COMMIT.
#   tools/regenerate.sh [COMMIT]
set -eu
COMMIT=${1:-$(cat tools/SNOWBALL_COMMIT)}
ROOT=$(cd "$(dirname "$0")/.." && pwd)
WORK="$ROOT/.scratch/snowball-src"
[ -d "$WORK" ] || git clone -q https://github.com/snowballstem/snowball.git "$WORK"
git -C "$WORK" fetch -q origin
git -C "$WORK" checkout -q "$COMMIT"
make -C "$WORK" -j8 snowball >/dev/null
rm -rf "$ROOT/generated" "$ROOT/runtime"
mkdir -p "$ROOT/generated" "$ROOT/runtime"
for sbl in $(LC_ALL=C ls "$WORK"/algorithms/*.sbl); do
	lang=$(basename "$sbl" .sbl)
	(cd "$ROOT/generated" && "$WORK/snowball" "$sbl" -o "stem_UTF_8_$lang" -eprefix "kronuz_snowball_${lang}_" -r ../runtime -u)
done
cp "$WORK"/runtime/*.c "$WORK"/runtime/*.h "$ROOT/runtime/"
cp "$WORK/COPYING" "$ROOT/LICENSE-SNOWBALL"
# Prefix every external runtime symbol and the runtime's struct names, so the library
# links beside libstemmer or another copy of the Snowball runtime.
syms=$(sed -n 's/^extern [^(]*[ *]\([A-Za-z_][A-Za-z0-9_]*\)(.*/\1/p' "$ROOT"/runtime/*.h | sort -u | tr '\n' '|')
perl -pi -e "s/\\b(${syms}SN_env|among)\\b/kronuz_snowball_\$1/g" "$ROOT"/runtime/* "$ROOT"/generated/*.[ch]
grep -v '^#' "$WORK/libstemmer/modules.txt" | awk 'NF' > "$ROOT/tools/modules.txt"
echo "$COMMIT" > "$ROOT/tools/SNOWBALL_COMMIT"
# generated/languages.inc: SNOWBALL_LANGUAGE(name, "alias,alias,...") for each algorithm.
{
	echo "// Generated by tools/regenerate.sh from Snowball's modules.txt. Do not edit."
	for sbl in $(LC_ALL=C ls "$WORK"/algorithms/*.sbl); do
		lang=$(basename "$sbl" .sbl)
		aliases=$(awk -v l="$lang" '$1 == l { print $3 }' "$ROOT/tools/modules.txt")
		echo "SNOWBALL_LANGUAGE($lang, \"${aliases:-$lang}\")"
	done
} > "$ROOT/generated/languages.inc"
# generated/stemmers.h: every generated header.
{
	echo "// Generated by tools/regenerate.sh. Do not edit."
	echo "#pragma once"
	echo "#include \"../runtime/api.h\""
	for sbl in $(LC_ALL=C ls "$WORK"/algorithms/*.sbl); do
		echo "#include \"stem_UTF_8_$(basename "$sbl" .sbl).h\""
	done
} > "$ROOT/generated/stemmers.h"
